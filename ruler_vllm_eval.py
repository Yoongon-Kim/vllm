"""RULER eval on the vLLM backends (FKV / LRoSA / Loki / FASA / Quest).

vLLM counterpart of pca's eval/ruler.py. Builds ONE vLLM engine for the chosen
backend (same build_llm dispatch as longbench_vllm_eval.py) and runs the
requested RULER synthetic tasks through it, scoring with the standard RULER
string-match metrics. Prepared data: <root>/<family>/<ctx_len>/<task>/validation.jsonl
(rows have `input` = full prompt text incl. template, `outputs` = list of
expected strings). Generated by SeerAttention/eval/ruler/data/prepare.py.

  CUDA_VISIBLE_DEVICES=0 HF_HOME=/NHNHOME/jiwonsong/hf_cache \
  VLLM_ENABLE_V1_MULTIPROCESSING=0 python ruler_vllm_eval.py \
    --mode lrosa --ctx_lens 32768 65536 --num_samples 25 \
    --tasks niah_multikey_2 niah_multikey_3 qa_1 qa_2 cwe \
    --n_fac 1024 --cs_h 32
"""
import argparse
import json
import os
import re
import sys

os.environ.setdefault("VLLM_USE_FLASHINFER_SAMPLER", "0")

from _bench_common import PCA_REPO, lrosa_basis_path, fasa_idom_path, yarn_overrides

from transformers import AutoTokenizer  # noqa: E402
from vllm import LLM, SamplingParams  # noqa: E402
from vllm.inputs import TokensPrompt  # noqa: E402

MODEL = "meta-llama/Llama-3.1-8B-Instruct"

# RULER task -> tokens_to_generate (RULER data/synthetic/constants.py).
_TOKENS_TO_GEN = {
    "niah_single_1": 128, "niah_single_2": 128, "niah_single_3": 128,
    "niah_multikey_1": 128, "niah_multikey_2": 128, "niah_multikey_3": 128,
    "niah_multivalue": 128, "niah_multiquery": 128,
    "vt": 30, "cwe": 120, "fwe": 50,
    "qa_1": 32, "qa_2": 32,
}
ALL_TASKS = list(_TOKENS_TO_GEN.keys())


def _string_match_all(preds, refs):
    """Avg over preds of (fraction of refs appearing as substrings). NIAH/VT/CWE/FWE."""
    if not preds:
        return 0.0
    total = 0.0
    for p, r in zip(preds, refs):
        if not r:
            continue
        total += sum(1.0 if ref.lower() in p.lower() else 0.0 for ref in r) / len(r)
    return round(total / len(preds) * 100, 2)


def _string_match_part(preds, refs):
    """Avg over preds of (1 if ANY ref is a substring, else 0). QA."""
    if not preds:
        return 0.0
    total = 0.0
    for p, r in zip(preds, refs):
        if not r:
            continue
        total += max(1.0 if ref.lower() in p.lower() else 0.0 for ref in r)
    return round(total / len(preds) * 100, 2)


def _metric_fn(task):
    return _string_match_part if task.startswith("qa") else _string_match_all


def _postprocess(s):
    return re.sub(r"[\x00-\x1f]", "\n", s.strip()).strip()


def _ruler_family(model):
    n = model.lower()
    if "llama" in n:
        return "llama"
    if "qwen3" in n:
        return "qwen3"
    if "gemma" in n:
        return "gemma"
    if "ministral-3" in n or "ministral3" in n or "mistral3" in n:
        return "ministral3"
    if "ministral" in n or "mistral" in n:
        return "mistral"
    if "glm" in n:
        return "glm"
    raise SystemExit(f"RULER family unknown for {model!r}")


def build_llm(a, max_model_len):
    """One vLLM engine for the chosen backend (mirrors longbench_vllm_eval)."""
    kw = dict(
        model=a.model,
        max_model_len=max_model_len,
        gpu_memory_utilization=a.gpu_mem,
        enforce_eager=a.eager,
        enable_prefix_caching=False,
    )
    # Ministral-3 is a Pixtral VLM; RULER is text-only -> disable image mm so vLLM
    # skips the dummy-image profiling that crashes MistralCommonPixtralProcessor.
    if any(s in a.model.lower() for s in ("ministral-3", "ministral3", "mistral3")):
        kw["limit_mm_per_prompt"] = {"image": 0}
    if a.max_num_seqs:
        kw["max_num_seqs"] = a.max_num_seqs
    if getattr(a, "yarn", True):
        ov = yarn_overrides(a.model)
        if ov:
            kw["hf_overrides"] = ov
    if a.mode in ("lrosa_mla", "loki_mla"):
        # LRoSA/Loki on an MLA model (GLM-4.7-Flash): score the latent c_KV.
        # MLA keeps its own latent cache -> kv_cache_dtype = mla_kv_dtype (fp8_ds_mla).
        basis = a.basis or lrosa_basis_path(
            a.model, cs_h=a.cs_h, variant="loki" if a.mode == "loki_mla" else "d1")
        kw["attention_config"] = {"lrosa_mla": True, "lrosa_basis_path": basis,
                                  "lrosa_n_fac": a.n_fac, "lrosa_cs_h": a.cs_h}
        kw["kv_cache_dtype"] = a.mla_kv_dtype
    elif a.mode in ("lrosa", "loki"):
        variant = "loki" if a.mode == "loki" else "d1"
        basis = a.basis or lrosa_basis_path(a.model, cs_h=a.cs_h, variant=variant)
        kw["kv_cache_dtype"] = "lrosa"
        ac = {
            "backend": "LROSA", "lrosa_basis_path": basis,
            "lrosa_n_fac": a.n_fac, "lrosa_cs_h": a.cs_h,
            "lrosa_use_radix_topk": True,
        }
        if a.fp8_projk:
            ac["lrosa_fp8_projk"] = True
        kw["attention_config"] = ac
    elif a.mode == "fasa":
        idom = a.basis or fasa_idom_path(a.model)
        kw["kv_cache_dtype"] = "fasa"
        kw["attention_config"] = {
            "backend": "LROSA", "lrosa_basis_path": idom,
            "lrosa_n_fac": a.n_fac, "lrosa_n_tip": a.n_tip,
            "lrosa_use_radix_topk": True,
        }
    elif a.mode == "quest":
        kw["kv_cache_dtype"] = "quest"
        kw["attention_config"] = {"backend": "QUEST", "quest_token_budget": a.n_fac}
    # fkv: dense default. GLM (MLA) dense -> fp8_e4m3 + TRITON_MLA (dense MLA can't
    # use fp8_ds_mla which is sparse-only); matches the lrosa_mla fp8 deployment.
    if a.mode == "fkv" and "glm" in a.model.lower():
        kw["kv_cache_dtype"] = "fp8_e4m3"
        if not a.mla_backend:
            a.mla_backend = "TRITON_MLA"
    if a.mla_backend:  # force/merge a specific MLA backend (head-count workaround)
        ac = kw.get("attention_config") or {}
        ac["backend"] = a.mla_backend
        kw["attention_config"] = ac
    if kw.get("kv_cache_dtype") in ("lrosa", "fasa", "quest", "seer"):
        # Hybrid models (Gemma 4, Ministral): window-bound the sliding layers'
        # KV cache instead of the combined-slot full-length cache. Output-
        # invariant (sliding attention is windowed either way); only cuts KV
        # memory / raises max batch. No-op for full-attention models.
        kw["kv_cache_dtype_skip_layers"] = ["sliding_window"]
    return LLM(**kw)


def load_rows(root, family, ctx_len, task, num_samples):
    path = os.path.join(root, family, str(ctx_len), task, "validation.jsonl")
    if not os.path.exists(path):
        raise SystemExit(f"RULER data not found: {path}\n"
                         f"Generate via SeerAttention prepare.py first.")
    rows = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))
            if num_samples and len(rows) >= num_samples:
                break
    return rows


def eval_one(llm, tok, root, family, ctx_len, task, a):
    rows = load_rows(root, family, ctx_len, task, a.num_samples)
    # RULER `input` already has the model template applied (prep --model_template_type).
    token_ids = [tok(r["input"], add_special_tokens=False).input_ids for r in rows]
    sp = SamplingParams(temperature=0.0, max_tokens=_TOKENS_TO_GEN[task])
    outs = llm.generate([TokensPrompt(prompt_token_ids=t) for t in token_ids],
                        sp, use_tqdm=False)
    preds, refs, recs = [], [], []
    for r, o in zip(rows, outs):
        pred = _postprocess(tok.decode(o.outputs[0].token_ids, skip_special_tokens=True))
        outputs = r.get("outputs") or r.get("answers") or []
        preds.append(pred)
        refs.append(outputs)
        recs.append({"prediction": pred, "outputs": outputs})
    score = _metric_fn(task)(preds, refs)
    return score, len(rows), recs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode",
                    choices=["fkv", "lrosa", "loki", "fasa", "quest", "lrosa_mla", "loki_mla"],
                    default="lrosa")
    ap.add_argument("--mla_kv_dtype", default="fp8_ds_mla",
                    help="MLA latent KV cache dtype (lrosa_mla/loki_mla). fp8_ds_mla = DSA sparse latent.")
    ap.add_argument("--mla_backend", default=None,
                    help="Force MLA attention backend (e.g. TRITON_MLA for GLM dense FKV, "
                         "FLASHMLA_SPARSE for lrosa_mla).")
    ap.add_argument("--model", default=MODEL)
    ap.add_argument("--ctx_lens", type=int, nargs="+", default=[32768, 65536])
    ap.add_argument("--tasks", nargs="+",
                    default=["niah_multikey_2", "niah_multikey_3", "qa_1", "qa_2", "cwe"],
                    help=f"Subset of {ALL_TASKS}")
    ap.add_argument("--num_samples", type=int, default=25, help="per (task, ctx_len). 0=all.")
    ap.add_argument("--ruler_data_root", default="/NHNHOME/jiwonsong/ruler_data")
    ap.add_argument("--n_fac", type=int, default=1024)
    ap.add_argument("--cs_h", type=int, default=32)
    ap.add_argument("--n_tip", type=int, default=16)
    ap.add_argument("--basis", default=None)
    ap.add_argument("--fp8_projk", action=argparse.BooleanOptionalAction, default=True)
    ap.add_argument("--yarn", action=argparse.BooleanOptionalAction, default=True)
    ap.add_argument("--eager", action="store_true")
    ap.add_argument("--max_num_seqs", type=int, default=4)
    ap.add_argument("--gpu_mem", type=float, default=0.90)
    ap.add_argument("--results_dir", default=os.path.join(PCA_REPO, "results", "ruler"))
    ap.add_argument("--run_name", required=True)
    a = ap.parse_args()

    family = _ruler_family(a.model)
    max_model_len = max(a.ctx_lens) + max(_TOKENS_TO_GEN[t] for t in a.tasks) + 64
    # Mistral: AutoTokenizer's LlamaTokenizer/mistral_common path drops inter-word
    # spaces (match collapse); force the Rust fast backend (matches longbench_vllm_eval).
    if "mistral" in a.model.lower():
        from transformers import PreTrainedTokenizerFast
        tok = PreTrainedTokenizerFast.from_pretrained(a.model)
    else:
        tok = AutoTokenizer.from_pretrained(a.model)
    llm = build_llm(a, max_model_len)

    run_dir = os.path.join(a.results_dir, a.model.split("/")[-1], a.run_name)
    os.makedirs(run_dir, exist_ok=True)
    print(f"  RULER results -> {run_dir}", flush=True)

    scores = {}  # ctx_len -> {task: score}
    for ctx_len in a.ctx_lens:
        scores[ctx_len] = {}
        for task in a.tasks:
            score, n, recs = eval_one(llm, tok, a.ruler_data_root, family, ctx_len, task, a)
            scores[ctx_len][task] = score
            print(f"[RULER] {a.mode:5s} {ctx_len:>6d} {task:18s} n={n:<3d} score={score:.2f}", flush=True)
            with open(os.path.join(run_dir, f"{ctx_len}_{task}.jsonl"), "w") as f:
                for rec in recs:
                    f.write(json.dumps(rec, ensure_ascii=False) + "\n")
            # incremental summary
            summary = {
                "run_name": a.run_name, "base_model": a.model, "mode": a.mode,
                "n_fac": a.n_fac, "cs_h": a.cs_h, "n_tip": a.n_tip,
                "num_samples": a.num_samples, "fp8_projk": bool(a.fp8_projk),
                "engine": "vllm", "scores": scores,
            }
            with open(os.path.join(run_dir, "summary.json"), "w") as f:
                json.dump(summary, f, indent=2); f.write("\n")

    print(f"\n=== RULER mode={a.mode} model={a.model} n_fac={a.n_fac} cs_h={a.cs_h} ===")
    for ctx_len in a.ctx_lens:
        row = scores[ctx_len]
        avg = sum(row.values()) / len(row) if row else 0.0
        print(f"  {ctx_len:>6d}: avg={avg:.2f}  " +
              "  ".join(f"{t}={row[t]:.1f}" for t in a.tasks))


if __name__ == "__main__":
    main()
